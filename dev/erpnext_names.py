"""Generate dev/erpnext-names.txt: every DocType and role name ERPNext defines (D-104, P1-20).

Run inside a container that has the ERPNext source (the pinned commit), from the bench folder:
    python3 erpnext_names.py apps/erpnext > erpnext-names.txt
dev/check_independence.py reads the committed snapshot, so the rule also runs where ERPNext is not installed.
"""

import glob
import json
import os
import sys

root = sys.argv[1] if len(sys.argv) > 1 else "apps/erpnext"
doctypes, roles = set(), set()
for path in glob.glob(os.path.join(root, "erpnext", "*", "doctype", "*", "*.json")):
	try:
		d = json.load(open(path, encoding="utf-8"))
	except (ValueError, OSError):
		continue
	if not isinstance(d, dict):
		continue
	if d.get("doctype") == "DocType" and os.path.basename(path)[:-5] == os.path.basename(os.path.dirname(path)):
		doctypes.add(d["name"])
	for p in d.get("permissions") or []:
		if p.get("role"):
			roles.add(p["role"])
for path in glob.glob(os.path.join(root, "erpnext", "*", "role", "*", "*.json")):
	try:
		d = json.load(open(path, encoding="utf-8"))
		roles.add(d.get("role_name") or d.get("name"))
	except (ValueError, OSError):
		continue
FRAPPE_ROLES = {"System Manager", "Administrator", "Guest", "All", "Desk User", "Website Manager", "Report Manager"}
print("# Generated by dev/erpnext_names.py from the pinned ERPNext source; one name per line, D: doctype, R: role.")
for n in sorted(doctypes):
	print(f"D: {n}")
for n in sorted(roles - FRAPPE_ROLES - {None}):
	print(f"R: {n}")
